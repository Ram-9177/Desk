export const uid = () => crypto.randomUUID();
export const now = () => new Date().toISOString();

// Queries use ? placeholders (turned into $1, $2 …). Inside tx() every helper runs on the transaction's client.
const txClient = new AsyncLocalStorage();
const toPg = sql => { let i = 0; return sql.replace(/\?/g, () => '$' + ++i); };
const query = (sql, a) => (txClient.getStore() || pool).query(toPg(sql), a.map(v => typeof v === 'boolean' ? Number(v) : v));
export const one = async (sql, ...a) => (await query(sql, a)).rows[0];
export const all = async (sql, ...a) => (await query(sql, a)).rows;
export const run = async (sql, ...a) => ({ changes: (await query(sql, a)).rowCount });
export async function tx(fn) {
  if (txClient.getStore()) return fn(); // already inside a transaction
  const c = await pool.connect();
  try {
    await c.query('BEGIN');
    const r = await txClient.run(c, fn);
    await c.query('COMMIT'); return r;
  } catch (e) { await c.query('ROLLBACK').catch(() => {}); throw e; }
  finally { c.release(); }
}
// returns the stored row, including defaults and generated ids
export const insert = (table, row) => {
  const k = Object.keys(row);
  return one(`INSERT INTO ${table} (${k.join(',')}) VALUES (${k.map(() => '?').join(',')}) RETURNING *`, ...k.map(x => row[x] ?? null));
};
export function hashPw(pw) {
  const salt = crypto.randomBytes(16).toString('hex');
  return salt + ':' + crypto.scryptSync(pw, salt, 64).toString('hex');
}
export function checkPw(pw, h) {
  if (!h) return false;
  const [salt, key] = h.split(':');
  return crypto.timingSafeEqual(Buffer.from(key, 'hex'), crypto.scryptSync(pw, salt, 64));
}
